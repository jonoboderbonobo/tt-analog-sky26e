#!/usr/bin/env python3
"""Writes the reference netlist (golden) of the tile top for LVS: tt_um_snn_mixed_golden.spice.
The macro dig_top comes from its own netlist (digital/macro/dig_top.spice, extracted by LibreLane); the 8 transmission gates are tg_cell
instances (analog/mux/tg_cell.sch via xschem); the connections are those of the design description: SEL/SELB/A/B/ties as in make_top.py.
Run from layout/:  python3 make_golden.py  (needs the netlist of tg_cell in ../analog/mux/lvs_run/tg_cell.spice, made by lvs_cell.sh)"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "digital", "librelane"))
import floorplan as fp

macro = open(os.path.join(HERE, "..", "digital", "macro", "dig_top.spice")).read()
m = re.search(r"^\.subckt dig_top ([^\n]*(?:\n\+[^\n]*)*)", macro, re.M)
mports = m.group(1).replace("\n+", " ").split()
tg = open(os.path.join(HERE, "..", "analog", "mux", "lvs_run", "tg_cell.spice")).read()

frame = ["clk", "ena", "rst_n"] + [f"{b}[{i}]" for b in ("ui_in", "uo_out", "uio_in", "uio_out", "uio_oe") for i in range(8)]
tile_ports = frame + [f"ua[{i}]" for i in range(8)] + ["VDPWR", "VGND"]     # the template def has 8 ua pads; 6 are routed in the tile, ua[2..7] are not used
rename = {"VPWR": "VDPWR", "VGND": "VGND"}

lines = [f"* reference netlist of tt_um_snn_mixed, generated by make_golden.py", macro.rstrip(), tg.rstrip()]
lines.append(".subckt tt_um_snn_mixed " + " ".join(tile_ports))
conn = []
for p in mports:
    if p in rename:
        conn.append(rename[p])
    elif p in ("osc_in",):
        conn.append("VGND")           # tied low: no oscillator block yet
    elif p in ("por_n_in",):
        conn.append("VDPWR")          # tied high: no POR block yet
    elif p in ("osc_en", "adc_en"):
        conn.append(p + "_unused")
    else:
        conn.append(p)
lines.append("Xdig " + " ".join(conn) + " dig_top")
for g in (0, 1):
    for k in range(4):
        lines.append(f"Xtg{g}_{k} a_sel{g}[{k}] a_selb{g}[{k}] ch{g}_{k} ua[{g}] VGND VDPWR tg_cell")
lines.append(".ends")
open(os.path.join(HERE, "tt_um_snn_mixed_golden.spice"), "w").write("\n".join(lines) + "\n")
print("golden written;", len(mports), "macro ports")
