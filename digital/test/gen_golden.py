#!/usr/bin/env python3
"""Golden vectors for snn_tiny from the bit-exact tinyODIN model of snn_gym (snn/tinyodin.py).

Usage (snn_gym needs numpy; its own venv has it):
  ~/working/MICMOSv2/snn_gym/.venv/bin/python gen_golden.py ~/working/MICMOSv2/snn_gym NN NI DEPTH > golden_NNxNI.txt

Line format, all integers:
  W row col value          weight write (row 0..NN+NI-1, value -8..7)
  T thr leak               threshold (0..4095) and leak (0..127), shared by all neurons
  E line                   input line event (row NN+line), then wait until idle     (host "quiet")
  R                        time-reference event, then wait until idle
  X s0 .. s(NN-1) c0 .. c(NN-1)   expected states after the previous E/R, and spikes per neuron during it
"""
import subprocess, sys
import numpy as np

gym, NN, NI, DEPTH = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
sys.path.insert(0, gym)
import snn.tinyodin as t                      # noqa: E402

t.FIFO_DEPTH = DEPTH                          # the hardware FIFO is DEPTH deep; the model's is 128
commit = subprocess.run(["git", "-C", gym, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
print(f"# snn_gym commit {commit}, NN={NN} NI={NI} DEPTH={DEPTH}, generated by gen_golden.py")

NR = NN + NI
CONFIGS = [  # density, weight range, thr, leak: a runaway network (never idle) gets thr raised until the model settles
    (0.5, 3, 6, 0), (1.0, 7, 10, 1), (0.3, 2, 4, 0), (1.0, 8, 12, 2), (0.7, 4, 8, 1), (1.0, 8, 5, 0),
    (1.0, 16, 4095, 0), (1.0, -16, 4095, 0)]   # last two: thr never reached, states saturate at +2047 / -2048


def run_config(cfg, thr_extra):
    density, wscale, thr, leak = CONFIGS[cfg]
    thr += thr_extra
    rng = np.random.default_rng(20261112 + cfg)
    W = np.zeros((256, NN), dtype=np.int32)
    if wscale > 0:
        block = rng.integers(-(wscale // 2), wscale, size=(NR, NN))      # biased positive: enough spikes
    else:
        block = rng.integers(wscale, 0, size=(NR, NN))                   # all negative
    W[:NR] = np.where(rng.random((NR, NN)) < density, np.clip(block, -8, 7), 0)
    lines = ["C"]
    lines += [f"W {r} {c} {int(W[r, c])}" for r in range(NR) for c in range(NN)]
    lines.append(f"T {thr} {leak}")
    m = t.TinyODIN(W, np.full(NN, thr), np.full(NN, leak), np.zeros(NN, dtype=bool), max_events_per_drain=5000)
    steps = 1400 if thr >= 4095 else 260
    for step in range(steps):
        if rng.random() < 0.25:
            m.aer_tref_all(); m.drain(); lines.append("R")
        else:
            line = int(rng.integers(0, NI)); m.aer_spike(NN + line); m.drain(); lines.append(f"E {line}")
        lines.append("X " + " ".join(str(int(x)) for x in [*m.state, *m.take_counts()]))
    print(f"# config {cfg}: thr {thr} leak {leak}: out_spikes {m.stats['out_spikes']} dropped {m.stats['dropped']} fifo_max {m.stats['fifo_max']}", file=sys.stderr)
    return lines


for cfg in range(len(CONFIGS)):
    for extra in range(0, 40, 2):
        try:
            print("\n".join(run_config(cfg, extra)))
            break
        except t.Runaway:
            continue
    else:
        raise SystemExit(f"config {cfg}: no settling threshold found")
